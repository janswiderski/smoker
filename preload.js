const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  listSmokeTests: () => ipcRenderer.invoke('list-smoke-tests'),
  listProjects: () => ipcRenderer.invoke('list-projects'),
  createProject: (name) => ipcRenderer.invoke('create-project', name),
  renameProject: (id, name) => ipcRenderer.invoke('rename-project', { id, name }),
  deleteProject: (id) => ipcRenderer.invoke('delete-project', id),
  chooseAddTestPlanMode: () => ipcRenderer.invoke('choose-add-test-plan-mode'),
  createBlankTestPlan: (name, projectId) => ipcRenderer.invoke('create-blank-test-plan', { name, projectId }),
  uploadSmokeTest: (projectId) => ipcRenderer.invoke('upload-smoke-test', projectId),
  deleteSmokeTest: (fileName) => ipcRenderer.invoke('delete-smoke-test', fileName),
  openEditor: (fileName) => ipcRenderer.invoke('open-editor', fileName),
  saveTestContent: (fileName, content) => ipcRenderer.invoke('save-test-content', { fileName, content }),
  downloadTestPlan: (fileName) => ipcRenderer.invoke('download-test-plan', fileName),
  downloadTestContent: (fileName, content) => ipcRenderer.invoke('download-test-content', { fileName, content }),
  startRun: (fileName) => ipcRenderer.invoke('start-run', fileName),
  takeScreenshot: (delayMs) => ipcRenderer.invoke('take-screenshot', delayMs),
  viewBaseline: () => ipcRenderer.invoke('view-baseline'),
  prevStep: () => ipcRenderer.invoke('prev-step'),
  nextStep: () => ipcRenderer.invoke('next-step'),
  endRun: () => ipcRenderer.invoke('end-run'),
  revealInFinder: (filePath) => ipcRenderer.invoke('reveal-in-finder', filePath),
  minimizeWindow: () => ipcRenderer.invoke('minimize-window'),
  openPath: (filePath) => ipcRenderer.invoke('open-path', filePath),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  openResults: (fileName) => ipcRenderer.invoke('open-results', fileName),
  listRuns: (fileName) => ipcRenderer.invoke('list-runs', fileName),
  getRunReport: (fileName, runId) => ipcRenderer.invoke('get-run-report', { fileName, runId }),
  deleteRun: (fileName, runId) => ipcRenderer.invoke('delete-run', { fileName, runId }),
  setRunAsBaseline: (fileName, runId) => ipcRenderer.invoke('set-run-as-baseline', { fileName, runId }),
  downloadCollage: (fileName, runId, stepId) => ipcRenderer.invoke('download-collage', { fileName, runId, stepId }),
  onStepUpdate: (callback) => ipcRenderer.on('step-update', (_event, data) => callback(data)),
  onResultsInit: (callback) => ipcRenderer.on('results-init', (_event, data) => callback(data)),
  onEditorInit: (callback) => ipcRenderer.on('editor-init', (_event, data) => callback(data)),
  onBaselinePreviewInit: (callback) => ipcRenderer.on('baseline-preview-init', (_event, data) => callback(data)),
});
